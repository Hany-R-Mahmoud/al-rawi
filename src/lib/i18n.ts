export type TranslationKey = keyof typeof messages.en;

export function translate(
  language: Language,
  key: TranslationKey,
  values: Record<string, string | number> = {}
): string {
  const suffix = language === "ar" ? (values.count === 1 ? "خلاصة" : "خلاصات") : values.count === 1 ? "" : "s";
  const template = messages[language][key] || messages.en[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => {
    if (name === "suffix" && values.suffix === undefined) return suffix;
    return String(values[name] ?? `{${name}}`);
  });
}
